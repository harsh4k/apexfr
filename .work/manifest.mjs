// Scans site/frames and writes site/js/shots.js
import { readdirSync, writeFileSync } from "node:fs";
const root = "X:/Projects/Websites/Webci/site/frames";
const out = {};
for (const shot of readdirSync(root)) {
  const tiers = readdirSync(`${root}/${shot}`).map(Number).filter(Boolean).sort((a, b) => a - b);
  const count = readdirSync(`${root}/${shot}/${tiers[0]}`).filter((f) => f.endsWith(".webp")).length;
  const portrait = tiers[tiers.length - 1] <= 1440 && shot.endsWith("v");
  out[shot] = { count, tiers, aspect: portrait ? 9 / 16 : 16 / 9, ...(shot === "loop" ? { fade: 28 } : {}) };
}
writeFileSync("X:/Projects/Websites/Webci/site/js/shots.js",
  `/* Generated by .work/manifest.mjs — frame sets available to the Director. */\nwindow.SHOTS = ${JSON.stringify(out, null, 2)};\n`);
console.log(out);
